//! `plane-migrate` binary: plan/check/apply over the mirrored SQL.
//!
//! The manifest generator lands with `[MIGRASI] Generator manifest + SQL
//! berkomentar`; until then every subcommand explains what is missing instead
//! of pretending to work.

use std::process::ExitCode;

fn main() -> ExitCode {
    let argument = std::env::args().nth(1).unwrap_or_default();
    match argument.as_str() {
        "--plan" | "--check" | "--apply" | "--validate" => {
            eprintln!(
                "plane-migrate: `{argument}` needs apps/api-rs/migrations/manifest.json, \
                 which is generated by the mirror generator card"
            );
            ExitCode::from(2)
        }
        "" | "--help" | "-h" => {
            println!("plane-migrate <--plan|--check|--apply|--validate>");
            ExitCode::SUCCESS
        }
        other => {
            eprintln!("plane-migrate: unknown argument `{other}`");
            ExitCode::from(64)
        }
    }
}
