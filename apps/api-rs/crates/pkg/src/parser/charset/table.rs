//! Every name CPython 3.12 resolves through `codecs.lookup()`.
//!
//! `CODEC_MODULES` mirrors the importable modules of the `encodings` package
//! that expose a registry entry; `CODEC_ALIASES` mirrors
//! `encodings.aliases.aliases`. `codecs.lookup()` does *not* simply replace
//! dots with underscores: it looks up an alias first, then imports the module
//! name, and skips module names that still contain a dot. Keeping the tables
//! separate reproduces that, including the surprise that `utf.8` is unknown
//! while `iso.8859.1` resolves.
//!
//! `Text` means `codecs.lookup()` succeeds and `''.encode(name)` succeeds;
//! `NonText` means lookup succeeds but encoding rejects it, which DRF reports
//! as 400. `Supported` names have a decoder in this crate; the rest of `Text`
//! is refused explicitly instead of being decoded with the wrong table (see
//! `docs/rust-api.md` §8.7).

use super::Charset;

/// What CPython does once a name has resolved to a codec module.
pub(super) enum CodecClass {
    /// The name maps to a decoder in this crate.
    Supported(Charset),
    /// `codecs.lookup()` and `''.encode()` both accept it.
    Text,
    /// `codecs.lookup()` accepts it, `''.encode()` rejects it (DRF: 400).
    NonText,
}

